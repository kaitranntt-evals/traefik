func verifyC2Conf(t *testing.T, gateways ...string) *dynamic.Configuration {
	t.Helper()
	secret := gateway.EvalIsoTLSSecretExported(t, "supersecret")
	eps := map[string]gateway.Entrypoint{"websecure": {Address: ":443"}}
	docs := []string{gateway.EvalIsoWhoamiYAML, gateway.EvalIsoClassYAML}
	for _, gw := range gateways {
		docs = append(docs,
			gateway.EvalIsoHTTPSGatewayExported("gw-"+gw, "supersecret", "catchall=", "precise="+gw+".example.com"),
			gateway.EvalIsoRouteExported("app-"+gw+"-catchall", "gw-"+gw, "catchall", "/"+gw+"-catchall"),
			gateway.EvalIsoRouteExported("app-"+gw+"-precise", "gw-"+gw, "precise", "/"+gw+"-precise"),
		)
	}
	return gateway.EvalIsoLoadExported(t, eps, []k8sruntime.Object{secret}, docs...)
}

func verifyC2Fallbacks(conf *dynamic.Configuration) []string {
	var names []string
	for name, r := range conf.HTTP.Routers {
		if r.Priority == 1 {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	return names
}

// verifyC2Label tags each fallback router with a response header naming it, so the fallback that
// served a 404 is observable through production handling. Statuses are also measured unlabelled.
func verifyC2Label(conf *dynamic.Configuration) {
	if conf.HTTP.Middlewares == nil {
		conf.HTTP.Middlewares = map[string]*dynamic.Middleware{}
	}
	for _, name := range verifyC2Fallbacks(conf) {
		mw := "verify-label-" + name
		conf.HTTP.Middlewares[mw] = &dynamic.Middleware{Headers: &dynamic.Headers{CustomResponseHeaders: map[string]string{"X-Verify-Fallback": name}}}
		conf.HTTP.Routers[name].Middlewares = append(conf.HTTP.Routers[name].Middlewares, mw)
	}
}

func TestVerifyC2_SiblingGatewayFallback(t *testing.T) {
	reqs := []struct{ desc, sni, host, path string }{
		{"A exact SNI, catch-all Host, unmatched path", "a.example.com", "xyz.example.org", "/nope"},
		{"B exact SNI, catch-all Host, unmatched path", "b.example.com", "xyz.example.org", "/nope"},
		{"control: catch-all SNI=Host, unmatched path", "xyz.example.org", "xyz.example.org", "/nope"},
		{"control: A exact SNI=Host, unmatched path", "a.example.com", "a.example.com", "/nope"},
		{"control: catch-all SNI, A exact Host, unmatched path", "xyz.example.org", "a.example.com", "/nope"},
		{"control: catch-all SNI, B exact Host, unmatched path", "xyz.example.org", "b.example.com", "/nope"},
	}

	for _, strict := range []bool{false, true} {
		t.Run(fmt.Sprintf("strictTLSOptions=%t", strict), func(t *testing.T) {
			t.Run("single gateway baseline (gw-a only)", func(t *testing.T) {
				conf := verifyC2Conf(t, "a")
				serve := evalServeHTTPSFull(t, conf, nil, "websecure", strict)
				for _, r := range reqs[:1] {
					t.Logf("SINGLE   %-52s sni=%-16s host=%-16s path=%s -> %d", r.desc, r.sni, r.host, r.path, serve(r.sni, r.host, r.path).Code)
				}
			})

			t.Run("sibling gateways (gw-a + gw-b)", func(t *testing.T) {
				conf := verifyC2Conf(t, "a", "b")
				for _, name := range verifyC2Fallbacks(conf) {
					r := conf.HTTP.Routers[name]
					t.Logf("FALLBACK %s rule=%s priority=%d entryPoints=%v tls.options=%q tls.gatewayListeners=%q service=%s", name, r.Rule, r.Priority, r.EntryPoints, r.TLS.Options, r.TLS.GatewayListeners, r.Service)
				}
				t.Logf("TLS options generated by provider: %d", len(conf.TLS.Options))

				serve := evalServeHTTPSFull(t, conf, nil, "websecure", strict)
				codes := map[string]int{}
				for _, r := range reqs {
					codes[r.desc] = serve(r.sni, r.host, r.path).Code
				}

				labelled := verifyC2Conf(t, "a", "b")
				verifyC2Label(labelled)
				serveL := evalServeHTTPSFull(t, labelled, nil, "websecure", strict)
				for _, r := range reqs {
					res := serveL(r.sni, r.host, r.path)
					served := res.Header.Get("X-Verify-Fallback")
					if i := strings.Index(served, "-gw-default-"); i >= 0 {
						served = served[i+1:]
					}
					t.Logf("SIBLING  %-52s sni=%-16s host=%-16s path=%s -> unlabelled=%d labelled=%d servedByFallback=%q", r.desc, r.sni, r.host, r.path, codes[r.desc], res.Code, served)
				}
				a, b := codes[reqs[0].desc], codes[reqs[1].desc]
				t.Logf("RESULT   A-direction=%d B-direction=%d (claim expects 421 for both; 404 on either = crossing reached a fallback)", a, b)
			})
		})
	}
}
